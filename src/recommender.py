def recommend_for_skill(skill, priority="Medium"):

    skill = str(skill).lower().strip()

    recommendation = LEARNING_RESOURCES.get(skill)

    if recommendation:
        return {
            "skill": skill,
            "priority": priority,
            "resources": recommendation["resources"],
            "practice": recommendation["practice"],
            "project": recommendation["project"]
        }

    return {
        "skill": skill,
        "priority": priority,
        "resources": [
            {
                "name": f"Search learning resources for {skill}",
                "url": f"https://www.google.com/search?q=learn+{skill.replace(' ', '+')}"
            }
        ],
        "practice": (
            f"Learn the fundamentals of {skill} and practice "
            "small exercises."
        ),
        "project": (
            f"Build a beginner project using {skill}."
        )
    }


def generate_recommendations(missing_skills, skill_gap_result=None):

    recommendations = []

    priority_map = {}

    if skill_gap_result:
        for item in skill_gap_result.get(
            "prioritized_missing_skills", []
        ):
            priority_map[
                str(item.get("skill", "")).lower().strip()
            ] = item.get("priority", "Medium")

    for skill in missing_skills:

        skill = str(skill).lower().strip()

        priority = priority_map.get(skill, "Medium")

        recommendation = recommend_for_skill(
            skill,
            priority
        )

        recommendations.append(recommendation)

    return recommendations